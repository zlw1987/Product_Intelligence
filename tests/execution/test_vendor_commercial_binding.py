class _RecordingFakeAdapter:
    """Counts constructions and lookup() calls; returns the canned response."""

    constructions = 0
    lookups = 0
    last_query = None
    canned = None

    def __init__(self) -> None:
        type(self).constructions += 1

    def lookup(self, query):
        type(self).lookups += 1
        type(self).last_query = query
        return type(self).canned


def _run_frozen_orchestration_path(response: CommercialSourceResponse) -> dict:
    """Run the (post-extraction) orchestration 4D-B path over a canned
    adapter response, exactly like the frozen 4D-B integration tests."""
    from product_intelligence.providers import internal_vendor as iv_mod
    import product_intelligence.execution.orchestration as orch

    _RecordingFakeAdapter.constructions = 0
    _RecordingFakeAdapter.lookups = 0
    _RecordingFakeAdapter.last_query = None
    _RecordingFakeAdapter.canned = response
    request = ResearchRequest(manufacturer_part_number=MPN, description=DESCRIPTION)
    with patch.dict(
        os.environ, {"PI_VENDOR_LOOKUP_BASE_URL": "http://vendor.internal/api"}
    ), patch.object(iv_mod, "InternalVendorAdapter", _RecordingFakeAdapter):
        payload = orch._try_vendor_commercial_lookup(None, request)
    assert payload is not None
    assert _RecordingFakeAdapter.constructions == 1
    assert _RecordingFakeAdapter.lookups == 1
    return payload


